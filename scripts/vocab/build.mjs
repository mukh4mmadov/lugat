import fs from "node:fs";
import { romanize } from "../romanize.mjs";

const MAX_DECK = 35;
const WORDS_DIR = "scripts/vocab/words";
const IDS_FILE = "scripts/vocab/ids.json";
const OUT_DIR = "data/vocab";

export const COURSES = [
  { id: "basics", topics: ["greet", "people", "family", "countries", "numbers", "time", "questions", "food", "home", "items", "shopping", "city", "study", "polite"] },
  { id: "everyday", topics: ["comm", "transport", "travel", "body", "health", "nature", "leisure", "sports", "daily", "verbs", "adjectives", "adverbs", "general"] },
];

const collator = new Intl.Collator("ko");
const columns = ["korean", "topic", "level", "uzbek", "english", "russian", "exKo", "exUz", "exEn", "exRu"];

const rows = fs
  .readdirSync(WORDS_DIR)
  .filter((name) => name.endsWith(".tsv"))
  .sort()
  .flatMap((name) =>
    fs
      .readFileSync(`${WORDS_DIR}/${name}`, "utf8")
      .split(/\r?\n/)
      .filter((line) => line.trim() && !line.startsWith("#"))
      .map((line) => {
        const cells = line.split("\t");
        if (cells.length !== columns.length) throw new Error(`${name}: ${cells.length} columns in "${cells[0]}"`);
        return Object.fromEntries(columns.map((column, index) => [column, cells[index].trim()]));
      }),
  );

const knownTopics = new Set(COURSES.flatMap((course) => course.topics));
const unknown = rows.filter((row) => !knownTopics.has(row.topic));
if (unknown.length) throw new Error(`Unknown topics: ${unknown.map((row) => `${row.korean}:${row.topic}`).join(", ")}`);

const ids = fs.existsSync(IDS_FILE) ? JSON.parse(fs.readFileSync(IDS_FILE, "utf8")) : {};
let nextId = Math.max(0, ...Object.values(ids)) + 1;
const idOf = (row) => {
  const key = `${row.korean}|${row.english}`;
  if (!ids[key]) ids[key] = nextId++;
  return ids[key];
};

const decks = [];
const deckWords = [];
for (const course of COURSES) {
  for (const topic of course.topics) {
    const words = rows.filter((row) => row.topic === topic).sort((a, b) => collator.compare(a.korean, b.korean) || a.english.localeCompare(b.english));
    if (!words.length) continue;
    const parts = Math.ceil(words.length / MAX_DECK);
    const size = Math.ceil(words.length / parts);
    for (let part = 1; part <= parts; part += 1) {
      const lesson = decks.length + 1;
      const chunk = words.slice((part - 1) * size, part * size);
      decks.push({ lesson, title: `${lesson}`, category: `deck.${topic}`, topic, part, parts, count: chunk.length, course: course.id });
      deckWords.push(
        chunk.map((row) => ({
          id: idOf(row),
          korean: row.korean,
          uzbek: row.uzbek,
          english: row.english,
          russian: row.russian,
          romanization: romanize(row.korean),
          lesson,
          theme: topic,
          level: Number(row.level) || 1,
          audio: "speechSynthesis:ko-KR",
          needsReview: false,
          example: { ko: row.exKo, uz: row.exUz, en: row.exEn, ru: row.exRu },
        })),
      );
    }
  }
}

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
const pad = (n) => String(n).padStart(2, "0");
fs.writeFileSync(`${OUT_DIR}/decks.json`, `${JSON.stringify(decks, null, 2)}\n`);
deckWords.forEach((words, index) => fs.writeFileSync(`${OUT_DIR}/deck-${pad(index + 1)}.json`, `${JSON.stringify(words, null, 2)}\n`));
fs.writeFileSync(IDS_FILE, `${JSON.stringify(ids, null, 2)}\n`);

const imports = deckWords.map((_, index) => `import deck${index + 1} from "../../data/vocab/deck-${pad(index + 1)}.json";`).join("\n");
fs.writeFileSync(
  "src/data/lessonsData.js",
  `// Generated by scripts/vocab/build.mjs: every topic deck's words. Kept out of
// the main bundle: src/data/index.js loads this chunk before the app renders
// (see dataReady), so it is cached apart from app code.
${imports}

export default [${deckWords.map((_, index) => `deck${index + 1}`).join(", ")}];
`,
);

console.log(`${rows.length} words in ${decks.length} decks`);
for (const deck of decks) console.log(`${deck.lesson}\t${deck.course}\t${deck.topic}${deck.parts > 1 ? ` ${deck.part}/${deck.parts}` : ""}\t${deck.count}`);
