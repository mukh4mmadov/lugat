// Builds src/data/korea/universities.js from official data only:
//   kosaf-tuition-2026.csv  KOSAF average tuition by university (data.go.kr 3071171, 2026-05-19)
//   ieqas-2025.json         MOJ/MOE certified and visa-scrutiny universities (2026-02-12)
//   curated.json            English names and websites from the universities' own sites
// Every fact keeps its source and date.
//
//   node scripts/korea-data/build-universities.mjs

import fs from "node:fs";
import { romanize } from "../romanize.mjs";

const dir = "scripts/korea-data";
const ieqas = JSON.parse(fs.readFileSync(`${dir}/ieqas-2025.json`, "utf8"));
const curated = JSON.parse(fs.readFileSync(`${dir}/curated.json`, "utf8")).universities;

const KOSAF = { url: "https://www.data.go.kr/data/3071171/fileData.do", date: "2026-05-19", publisher: "KOSAF" };
const IEQAS = { url: ieqas.source, date: ieqas.announced, publisher: "MOJ·MOE" };

const rows = fs
  .readFileSync(`${dir}/kosaf-tuition-2026.csv`, "utf8")
  .trim()
  .split(/\r?\n/)
  .slice(1)
  .map((line) => line.split(",").map((cell) => cell.replace(/^"|"$/g, "")));

const inList = (list, name) => Object.values(ieqas[list]).some((names) => names.includes(name));

// Branch campuses KOSAF reports together with the main university.
const PARENT = {
  "건국대학교(글로컬)": "건국대학교",
  "고려대학교(세종)": "고려대학교",
  "동국대학교(WISE)": "동국대학교",
  "연세대학교(미래)": "연세대학교",
  "한양대학교(ERICA)": "한양대학교",
};

// Where branch campuses and schools missing from KOSAF actually are.
const REGION = {
  "건국대학교(글로컬)": "충북",
  "고려대학교(세종)": "세종",
  "동국대학교(WISE)": "경북",
  "연세대학교(미래)": "강원",
  "한양대학교(ERICA)": "경기",
  "국립강릉원주대학교": "강원",
  "경남도립남해대학": "경남",
};

const slugOf = (name) =>
  romanize(name.replace(/\(.*\)/, ""))
    .replace(/daehakgyo$/, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "") + (name.includes("(") ? "-" + romanize(name.match(/\((.*)\)/)[1]).toLowerCase().replace(/[^a-z0-9]+/g, "") : "");

const byName = new Map();
for (const [kind, founding, name, region, quota, entrance, tuition] of rows) {
  if (/사이버|폴리텍|방송통신/.test(name)) continue; // online and vocational institutes are not for international degree students
  byName.set(name, {
    ko: name,
    kind: kind === "대학" ? "university" : "college",
    founding: founding === "국공립" ? "public" : "private",
    region,
    quota: Number(quota) || null,
    entranceFee: Math.round(Number(entrance)) || 0,
    tuition: Math.round(Number(tuition)) || null,
    tuitionNote: null,
  });
}

// Campuses and graduate schools that appear only in the IEQAS lists.
for (const list of ["certifiedDegree", "certifiedLanguage", "visaScrutinyDegree", "visaScrutinyLanguage"]) {
  for (const [group, names] of Object.entries(ieqas[list])) {
    for (const name of names) {
      if (byName.has(name)) continue;
      const parent = byName.get(PARENT[name]);
      byName.set(name, {
        ko: name,
        kind: group === "graduate" ? "graduate" : group,
        founding: parent?.founding || null,
        region: REGION[name] || parent?.region || null,
        quota: null,
        entranceFee: parent ? parent.entranceFee : null,
        tuition: parent ? parent.tuition : null,
        tuitionNote: parent ? "parent" : null,
      });
    }
  }
}

const universities = [...byName.values()].map((entry) => {
  const extra = curated[entry.ko] || {};
  const degree = inList("visaScrutinyDegree", entry.ko) ? "scrutiny" : inList("certifiedDegree", entry.ko) ? "certified" : "none";
  const language = inList("visaScrutinyLanguage", entry.ko) ? "scrutiny" : inList("certifiedLanguage", entry.ko) ? "certified" : "none";
  const sources = [];
  if (entry.tuition) sources.push({ field: "tuition", ...KOSAF, ...(entry.tuitionNote ? { note: "main campus average" } : {}) });
  sources.push({ field: "ieqas", ...IEQAS });
  if (extra.site) sources.push({ field: "site", url: extra.site, publisher: "university" });
  return {
    id: slugOf(entry.ko),
    ...entry,
    en: extra.en || null,
    romanized: romanize(entry.ko),
    site: extra.site || null,
    ieqas: { degree, language, excellent: inList("excellent", entry.ko) },
    featured: Boolean(extra.en),
    sources,
  };
});

// Slugs must be unique.
const seen = new Map();
universities.forEach((uni) => {
  const count = seen.get(uni.id) || 0;
  seen.set(uni.id, count + 1);
  if (count) uni.id = `${uni.id}-${count + 1}`;
});

universities.sort((a, b) => Number(b.featured) - Number(a.featured) || (b.ieqas.degree === "certified") - (a.ieqas.degree === "certified") || a.ko.localeCompare(b.ko, "ko"));

const header = `// Generated by scripts/korea-data/build-universities.mjs from official sources
// (KOSAF tuition ${KOSAF.date}, MOJ/MOE IEQAS list ${IEQAS.date}). Do not edit by hand:
// fix the source files and rebuild, or use the admin content editor.
`;
fs.mkdirSync("src/data/korea", { recursive: true });
fs.writeFileSync(
  "src/data/korea/universities.js",
  `${header}\nexport const SOURCES = ${JSON.stringify({ kosaf: KOSAF, ieqas: { ...IEQAS, note: ieqas.note } }, null, 2)};\n\nexport const UNIVERSITIES = ${JSON.stringify(universities)};\n`,
);

const stats = {
  total: universities.length,
  withTuition: universities.filter((uni) => uni.tuition).length,
  certifiedDegree: universities.filter((uni) => uni.ieqas.degree === "certified").length,
  scrutiny: universities.filter((uni) => uni.ieqas.degree === "scrutiny" || uni.ieqas.language === "scrutiny").length,
  featured: universities.filter((uni) => uni.featured).length,
};
console.log(stats);
const missingCurated = Object.keys(curated).filter((name) => !byName.has(name));
if (missingCurated.length) console.log("curated names not found:", missingCurated);
