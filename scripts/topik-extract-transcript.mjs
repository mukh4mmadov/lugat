// Builds per-question listening transcripts from a TOPIK "듣기 대본" PDF, for
// the result review ("audio text") and the AI explanation of mistakes.
//
//   node scripts/topik-extract-transcript.mjs <script.pdf> <out.js> <EXPORT_NAME> [questions=30]
//
// Questions 1-24 print their conversation after the "N." header; the
// "listen and answer" pairs print one conversation after the block header,
// shared by both questions. Choice lines (①-④) and page furniture are dropped.
import fs from "node:fs";
import { getDocument } from "pdfjs-dist/legacy/build/pdf.mjs";

const [pdfPath, outPath, exportName = "TRANSCRIPT", count = "30"] = process.argv.slice(2);
if (!pdfPath || !outPath) {
  console.error("Usage: node scripts/topik-extract-transcript.mjs <script.pdf> <out.js> <EXPORT_NAME> [questions]");
  process.exit(1);
}

const pdf = await getDocument({ data: new Uint8Array(fs.readFileSync(pdfPath)), useSystemFonts: true }).promise;
const lines = [];
for (let number = 1; number <= pdf.numPages; number += 1) {
  const page = await pdf.getPage(number);
  const { items } = await page.getTextContent();
  let line = "";
  let lastY = null;
  for (const item of items) {
    const y = Math.round(item.transform[5]);
    if (lastY !== null && Math.abs(y - lastY) > 3) {
      lines.push(line);
      line = "";
    }
    line += item.str;
    lastY = y;
  }
  lines.push(line);
}

const tidy = (text) =>
  text
    // Stage directions for the voice actors, e.g. "(잠시 후)", "(…느낌)".
    .replace(/\((?:잠시 후|[^)]*느낌)\)/g, "")
    .replace(/\s*:\s*/g, ": ")
    .replace(/([,.?!])(?=[^\s\d.,?!)"'])/g, "$1 ")
    .replace(/\s+/g, " ")
    .trim();

const isFurniture = (line) => !line.trim() || /한국어능력시험/.test(line) || /^\s*\d+\s*$/.test(line) || /듣기 통합/.test(line);
const transcripts = {};
let block = null; // { from, to, text: [] }
let current = null; // { number, text: [] }

const flush = () => {
  if (current) transcripts[current.number] = current.text;
  current = null;
};

for (const raw of lines) {
  if (isFurniture(raw)) continue;
  const line = raw.trim();
  const blockMatch = line.match(/^※\s*\[(\d+)\s*～\s*(\d+)\]/);
  if (blockMatch) {
    flush();
    block = { from: Number(blockMatch[1]), to: Number(blockMatch[2]), shared: /물음에 답하십시오/.test(line), text: [], inExample: false };
    continue;
  }
  const questionMatch = line.match(/^(\d{1,2})\.\s*/);
  if (questionMatch && Number(questionMatch[1]) >= 1 && Number(questionMatch[1]) <= Number(count)) {
    flush();
    const number = Number(questionMatch[1]);
    // Pairs: the conversation was printed before the first question.
    current = { number, text: block?.shared ? [...block.text] : [] };
    // Single questions often start their conversation on the header line;
    // in pairs the rest of that line is the printed question.
    const rest = line.slice(questionMatch[0].length).replace(/\(\s*\d\s*점\s*\)/, "").trim();
    if (rest && !block?.shared) current.text.push(rest);
    continue;
  }
  if (/^[①②③④❶❷❸❹]/.test(line)) continue;
  if (/^<\s*보\s*기\s*>/.test(line)) {
    if (block) block.inExample = true;
    continue;
  }
  if (current) {
    if (!block?.shared) current.text.push(line);
  } else if (block && !block.inExample) {
    block.text.push(line);
  }
}
flush();

// Join wrapped lines; a new speaker starts a new line.
const result = {};
const problems = [];
for (let number = 1; number <= Number(count); number += 1) {
  const parts = transcripts[number];
  if (!parts?.length) {
    problems.push(number);
    continue;
  }
  const speakers = [];
  for (const part of parts) {
    if (/^(여자|남자|가|나)\s*:/.test(part) || !speakers.length) speakers.push(part);
    else speakers[speakers.length - 1] += ` ${part}`;
  }
  result[number] = speakers.map(tidy).filter((text) => !/_{3,}/.test(text) || text.length > 8).join("\n");
}
if (problems.length) {
  console.error(`No transcript for questions: ${problems.join(", ")}`);
  process.exit(1);
}

const banner = `// Generated by scripts/topik-extract-transcript.mjs from the listening script
// (듣기 대본): what is said in each listening question. Regenerate instead of
// editing by hand.

`;
const body = Object.entries(result).map(([number, text]) => `  ${number}: ${JSON.stringify(text)},`).join("\n");
fs.writeFileSync(outPath, `${banner}export const ${exportName} = {\n${body}\n};\n`);
console.log(`Wrote ${Object.keys(result).length} transcripts to ${outPath}`);
