// Writes src/data/stories/public.js, the stories the app ships to everyone.
// Free stories are whole; a Premium story keeps its title, words and opening
// lines, and its full text and questions come from /api/rewards?story=<id>
// for learners with Premium. Runs before `vite build`.
//
//   node scripts/split-stories.mjs

import fs from "node:fs";
import { FULL_STORIES, isPremiumStoryId } from "../src/data/stories/full.js";

const OPENING_LINES = 2;
const stories = FULL_STORIES.map((story) =>
  isPremiumStoryId(story.id) ? { ...story, lines: story.lines.slice(0, OPENING_LINES), questions: [], teaser: true } : story,
);
const body = stories.map((story) => `  ${JSON.stringify(story)},`).join("\n");
fs.writeFileSync(
  "src/data/stories/public.js",
  `// Generated by scripts/split-stories.mjs from ./full.js. Do not edit: change\n// the lessons files and run the script (npm run build does).\n\nexport default [\n${body}\n];\n`,
);
console.log(`Wrote ${stories.length} stories, ${stories.filter((story) => story.teaser).length} as Premium openings`);
