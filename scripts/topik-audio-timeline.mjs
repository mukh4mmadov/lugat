// Finds where each listening question sits in a TOPIK recording, so the exam
// can follow the audio question by question (like the computer-based test)
// and practice mode can replay a single question.
//
//   FFMPEG=/path/to/ffmpeg node scripts/topik-audio-timeline.mjs <listening.mp3> <out.js> <EXPORT_NAME> [questions=30]
//
// Every question in a TOPIK recording ends with a long silence for answering
// (20-40 s); everything else (pauses between the two readings, instructions)
// is much shorter. The script detects silences with ffmpeg and requires
// exactly one long silence per question. Times are in seconds:
//   start      where the question's audio begins (its block instruction included)
//   speechEnd  where the answering silence begins
//   end        where the answering silence ends
import { spawnSync } from "node:child_process";
import fs from "node:fs";

const [audioPath, outPath, exportName = "AUDIO_TIMELINE", count = "30"] = process.argv.slice(2);
const ffmpeg = process.env.FFMPEG || "ffmpeg";
if (!audioPath || !outPath) {
  console.error("Usage: FFMPEG=ffmpeg node scripts/topik-audio-timeline.mjs <listening.mp3> <out.js> <EXPORT_NAME> [questions]");
  process.exit(1);
}

const ANSWER_GAP = 15; // seconds; longer silences are answering time
// ffmpeg writes its report, including the detected silences, to stderr.
const run = spawnSync(ffmpeg, ["-hide_banner", "-i", audioPath, "-af", "silencedetect=noise=-35dB:d=2.5", "-f", "null", "-"], { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 });
const output = `${run.stdout || ""}${run.stderr || ""}`;
const silences = [...output.matchAll(/silence_end: ([\d.]+) \| silence_duration: ([\d.]+)/g)].map((match) => {
  const end = Number(match[1]);
  return { start: end - Number(match[2]), end };
});
if (!silences.length) {
  console.error("No silences found. Is FFMPEG set to a working ffmpeg binary?");
  process.exit(1);
}

const gaps = silences.filter((silence) => silence.end - silence.start >= ANSWER_GAP);
if (gaps.length !== Number(count)) {
  console.error(`Expected ${count} answering silences, found ${gaps.length}. Check the recording or ANSWER_GAP.`);
  process.exit(1);
}

// The first question starts after the general introduction: at the end of the
// longest silence before its answering time.
const intro = silences.filter((silence) => silence.end <= gaps[0].start).sort((a, b) => (b.end - b.start) - (a.end - a.start))[0];
const round = (value) => Math.round(value * 10) / 10;
const timeline = {};
gaps.forEach((gap, index) => {
  const start = index === 0 ? intro?.end ?? 0 : gaps[index - 1].end;
  timeline[index + 1] = { start: round(start), speechEnd: round(gap.start), end: round(gap.end) };
});

const banner = `// Generated by scripts/topik-audio-timeline.mjs from ${audioPath.replace(/\\/g, "/")}:
// where each listening question's audio starts, where its answering silence
// begins, and where that silence ends (seconds). Regenerate instead of editing.

`;
const body = Object.entries(timeline).map(([number, value]) => `  ${number}: ${JSON.stringify(value)},`).join("\n");
fs.writeFileSync(outPath, `${banner}export const ${exportName} = {\n${body}\n};\n`);
console.log(`Wrote ${Object.keys(timeline).length} questions to ${outPath}`);
for (const [number, value] of Object.entries(timeline)) {
  console.log(number.padStart(2), `${value.start.toFixed(1)}s`, `speech ${(value.speechEnd - value.start).toFixed(1)}s`, `answer ${(value.end - value.speechEnd).toFixed(1)}s`);
}
